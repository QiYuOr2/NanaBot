/** 归一化后的现代词，命中时不再剥掉词尾语气词，避免「蚌埠住了」变成「蚌埠住」。 */
export const MODERN_WORD_SET: ReadonlySet<string> = new Set(
  MODERN_DICT_WORDS.map((word) => word.normalize("NFKC").replace(/\s+/gu, "").toLowerCase()),
);

/** jieba `loadDict` 用的二进制词表。词频取高，让整词压过内置词典的错误切分。 */
export function encodeModernDict(): Uint8Array {
  const lines = MODERN_DICT_WORDS.map((word) => `${word} 100000 n`);
  return new TextEncoder().encode(lines.join("\n"));
}
